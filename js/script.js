const shoeRow = document.getElementById("shoe-row");

const randershoes = (list) => {
    shoeRow.innerHTML = "";

    if (list.length === 0) {
        shoeRow.innerHTML = '<p class="text-white fs-4">No shoes found.</p>';
        return;
    }

    list.forEach((shoe) => {
        const shoeCard = document.createElement("div");
        shoeCard.classList.add("col-12", "col-sm-6", "col-md-4", "col-lg-3", "mb-4");

        shoeCard.innerHTML = `
        <div class="card">
            <img src="${shoe.image}" class="card-img-top" alt="${shoe.name}">
            <div class="card-body bg-black text-white m-0">
                <h5 class="card-title">${shoe.name}</h5>
                <p class="card-text badge bg-secondary text-white p-2 mt-3">Price: $${shoe.price}</p>
                <p class="card-text badge bg-secondary text-white p-2 mt-3">Color: ${shoe.color}</p>
                <p class="card-text badge bg-secondary text-white p-2 mt-3">Size: ${shoe.size}</p>
            </div>
        </div>
        `;
        shoeRow.appendChild(shoeCard);
    });
};

const inPrice = (p, range) => {
    if (range === "all") return true;
    if (range.endsWith("+")) return p >= parseInt(range);
    const [min, max] = range.split("-").map(Number);
    return p >= min && p <= max;
};

const searchProducts = () => {
    const brand = document.getElementById("brand").value;
    const color = document.getElementById("color").value;
    const size = document.getElementById("size").value;
    const price = document.getElementById("price").value;

    const result = shoes.filter((s) =>
        (brand === "all" || s.brand === brand) &&
        (color === "all" || s.color === color) &&
        (size === "all" || s.size === size) &&
        inPrice(s.price, price)
    );
    randershoes(result);
};

randershoes(shoes);